class UNet(torch.nn.Module):
    def __init__(self, in_channels=3, num_classes=NUM_CLASSES, bilinear=False, base=32):
        super(UNet, self).__init__()
        self.in_channels = in_channels
        self.num_classes = num_classes
        self.bilinear = bilinear
        self.base = base

        factor = 2 if bilinear else 1

        self.inc   = DoubleConv(in_channels, base)
        self.down1 = Down(base,     base * 2)
        self.down2 = Down(base * 2, base * 4)
        self.down3 = Down(base * 4, base * 8)
        self.down4 = Down(base * 8, (base * 16) // factor)

        self.up1 = Up(base * 16, (base * 8) // factor, bilinear)
        self.up2 = Up(base * 8,  (base * 4) // factor, bilinear)
        self.up3 = Up(base * 4,  (base * 2) // factor, bilinear)
        self.up4 = Up(base * 2,  base, bilinear)

        self.outc = OutConv(base, num_classes)

    def forward(self, x):
        x1 = self.inc(x)
        x2 = self.down1(x1)
        x3 = self.down2(x2)
        x4 = self.down3(x3)
        x5 = self.down4(x4)
        x = self.up1(x5, x4)
        x = self.up2(x, x3)
        x = self.up3(x, x2)
        x = self.up4(x, x1)
        return self.outc(x)